import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {writeFile,mkdir} from 'node:fs/promises';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage();page.on('dialog',d=>d.accept());
const truth=[{name:'合成半导体指数A',value:'12345.67'},{name:'合成医疗指数C',value:'8096.25'}];
try{
 await page.goto(process.env.BASE_URL||'http://127.0.0.1:4318');
 const png=await page.evaluate(rows=>{
 const c=document.createElement('canvas');c.width=1080;c.height=820;const x=c.getContext('2d');x.fillStyle='#fff';x.fillRect(0,0,c.width,c.height);x.fillStyle='#202632';
 x.font='32px "Microsoft YaHei"';x.fillText('合成测试 · 基金持有',40,80);x.font='26px "Microsoft YaHei"';x.fillText('基金名称',40,170);x.fillText('持有金额(元)',490,170);x.fillText('持有收益',820,170);
 rows.forEach((r,i)=>{const y=280+i*220;x.font='30px "Microsoft YaHei"';x.fillText(r.name,40,y);x.fillText(Number(r.value).toLocaleString('en-US',{minimumFractionDigits:2}),490,y);x.fillText(i?'-56.78':'+123.45',820,y);x.fillText(i?'-0.70%':'+2.30%',820,y+60);});
 return c.toDataURL('image/png').split(',')[1];},truth);
 await mkdir('artifacts',{recursive:true});await writeFile('artifacts/alipay-style-synthetic.png',Buffer.from(png,'base64'));
 await page.locator('[data-action="import"]').first().click();await page.locator('#image-input').setInputFiles({name:'synthetic.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')});await page.locator('#canvas-host canvas').waitFor();await page.locator('[data-action="recognize"]').click();await page.locator('[data-action="cancel-ocr"]').waitFor({state:'detached',timeout:150000});
 const rows=await page.locator('[data-row]').evaluateAll(els=>els.map(el=>({name:el.querySelector('[data-field="name"]').value,value:el.querySelector('[data-field="marketValue"]').value,currency:el.querySelector('[data-field="currency"]').value})));
 await writeFile('artifacts/alipay-style-ocr.json',JSON.stringify({synthetic:true,rows,truth},null,2));
 assert.deepEqual(rows.map(({name,value})=>({name:name.replaceAll(' ',''),value})),truth);assert.ok(rows.every(r=>r.currency==='CNY'));
 const first=page.locator('[data-row="0"]');
 assert.equal(await first.locator('[data-name-evidence] canvas').count(),1,'name crop must be shown beside candidate');
 assert.match(await first.locator('.name-review').innerText(),/逐字/);
 await first.locator('[data-field="ready"]').check();
 await first.locator('[data-field="name"]').fill('合成修正名称A');
 await first.locator('[data-field="marketValue"]').focus();
 assert.equal(await first.locator('[data-field="ready"]').isChecked(),false,'editing a confirmed field must require re-review');
 assert.equal(await first.locator('[data-field="name"]').inputValue(),'合成修正名称A');
 await page.setViewportSize({width:390,height:844});
 assert.ok(await first.locator('[data-name-evidence] canvas').isVisible());
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'mobile page must fit');
 await page.screenshot({path:'artifacts/name-review-mobile.png',fullPage:true});
 await first.locator('[data-field="ready"]').check();
 await page.locator('[data-row="1"] [data-field="ready"]').check();
 await page.locator('[data-action="preview"]').click();
 await page.locator('[data-action="apply"]').click();
 await page.locator('[data-action="data"]').first().click();
 const downloading=page.waitForEvent('download');await page.locator('[data-action="export-data"]').click();const download=await downloading;
 const fs=await import('node:fs/promises');const backup=await fs.readFile(await download.path(),'utf8');
 assert.doesNotMatch(backup,/originalName|nameRegion|nameEvidence|data:image|识别原名称/,'OCR evidence must not enter backup');
 assert.match(backup,/合成修正名称A/);
 await page.locator('[data-action="import"]').first().click();
 await page.locator('#text-recovery summary').click();
 await page.locator('#paste-text').fill('产品名称：合成全球…\n持仓金额：100\n产品名称：合成科技(QDII\n持仓金额：200');
 await page.locator('[data-action="parse-paste"]').click();
 assert.match(await page.locator('[data-row="0"] .name-review').innerText(),/省略/);
 assert.match(await page.locator('[data-row="1"] .name-review').innerText(),/括号/);
 assert.equal(await page.locator('[data-name-evidence]').count(),0,'pasted text must not inherit old image snippets');
 assert.equal(await page.locator('[data-row="0"] [data-field="name"]').inputValue(),'合成全球…','truncated names stay unfilled');
 console.log('Name crop, editing re-review, mobile layout and evidence-free backup passed using actual synthetic OCR.');
}finally{await browser.close();}
